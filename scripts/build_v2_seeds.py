def record(identifier, family, task, texts, **meta):
    return {"id": identifier, "case_id": family, "task": task,
            "source": "author_created_v2_teaching_seed", "review_status": "unreviewed",
            "seed_asset_version": "v2-seeds-v1", **meta,
            "messages": [{"role": "user" if i % 2 == 0 else "assistant", "content": text} for i, text in enumerate(texts)]}


